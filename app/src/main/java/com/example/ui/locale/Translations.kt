    fun get(key: String, language: AppLanguage): String {
        return when (language) {
            AppLanguage.ENGLISH -> en[key] ?: key
            AppLanguage.HINDI -> hi[key] ?: key
            AppLanguage.MARATHI -> mr[key] ?: key
        }
    }
