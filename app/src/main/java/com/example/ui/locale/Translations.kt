// CompositionLocal to supply language context down the Composable hierarchy
val LocalLanguage: ProvidableCompositionLocal<AppLanguage> = compositionLocalOf { AppLanguage.ENGLISH }

@Composable
fun getStr(key: String): String {
    val currentLanguage = LocalLanguage.current
    return remember(key, currentLanguage) {
        Strings.get(key, currentLanguage)
    }
}
